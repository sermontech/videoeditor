export function validateFootball(v) {
  if (!v || !footballPresets.some((p) => p.id === v.preset))
    throw Error("Unknown football preset.");
  for (const k of ["primary", "secondary"])
    if (!/^#[0-9a-f]{6}$/i.test(v[k])) throw Error("Invalid team colour.");
  for (const [k, min, max] of [
    ["light", 0.25, 2],
    ["crowd", 0, 1],
    ["x", -3, 3],
    ["z", -3, 3],
    ["y", -1, 2],
    ["rotation", -180, 180],
    ["scale", 0.25, 2],
  ])
    if (!Number.isFinite(v[k]) || v[k] < min || v[k] > max)
      throw Error(`Invalid football ${k}.`);
  for (const k of ["animated", "safeZones"])
    if (typeof v[k] !== "boolean") throw Error("Invalid football toggle.");
  return v;
}
export function fitHeight(bounds) {
  const h = bounds.max.y - bounds.min.y;
  if (!Number.isFinite(h) || h <= 0)
    throw Error("Model has no measurable height.");
  return 1.8 / h;
}
